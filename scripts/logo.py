"""Extracts Cero's vector logo from the cover of their own Code of Conduct PDF and writes lib/logo.ts.

The live site only serves the logo as PNG (Cero_RGB_Colour_POS.png / _NEG.png). The Code of Conduct (2026,
uploads/2026/04/Cero-Code-of-Conduct-A5-web.pdf, made in Affinity Publisher) carries the real vectors on page 1:
  4 letter paths  c e r o            (white on the cover; navy #2c2a6d on its back page)
  2 swirl paths   the two crescents  (#fecb39) that make the ring above the o
  2 large swirls  the same mark at cover scale (decorative), written to public/media/swirl.svg
Run: python3 scripts/logo.py   (needs PyMuPDF: pip install pymupdf). Download the PDF with scripts/media.sh first.
"""
import json, fitz

doc = fitz.open("_scrape/raw/Cero-Code-of-Conduct-A5-web.pdf")
drawings = doc[0].get_drawings()

def to_d(drawing, ox, oy, s=1.0):
    out, cur = [], None
    for it in drawing["items"]:
        op = it[0]
        a, b = (it[1], it[2]) if op == "l" else (it[1], it[4])
        if cur is None or abs(cur.x - a.x) > 1e-3 or abs(cur.y - a.y) > 1e-3:
            if out: out.append("Z")
            out.append(f"M{(a.x-ox)*s:.2f} {(a.y-oy)*s:.2f}")
        if op == "l": out.append(f"L{(b.x-ox)*s:.2f} {(b.y-oy)*s:.2f}")
        else: out.append(f"C{(it[2].x-ox)*s:.2f} {(it[2].y-oy)*s:.2f} {(it[3].x-ox)*s:.2f} {(it[3].y-oy)*s:.2f} {(b.x-ox)*s:.2f} {(b.y-oy)*s:.2f}")
        cur = b
    out.append("Z")
    return "".join(out)

# Indices on the cover page, checked by fill colour and bounds (scripts/logo.py prints them with --list).
parts = {"c": 8, "e": 11, "r": 9, "o": 10, "swirlA": 6, "swirlB": 7}
rects = [drawings[i]["rect"] for i in parts.values()]
x0, y0 = min(r.x0 for r in rects), min(r.y0 for r in rects)
x1, y1 = max(r.x1 for r in rects), max(r.y1 for r in rects)
S = 4  # scale up so the numbers stay readable at 2 decimals
paths = {k: to_d(drawings[i], x0, y0, S) for k, i in parts.items()}
w, h = (x1 - x0) * S, (y1 - y0) * S
# The ring on its own (for the favicon and the preloader's centre), in its own frame.
ring = [drawings[parts["swirlA"]]["rect"], drawings[parts["swirlB"]]["rect"]]
rx0, ry0 = min(r.x0 for r in ring), min(r.y0 for r in ring)
rx1, ry1 = max(r.x1 for r in ring), max(r.y1 for r in ring)

ts = f'''// Generated by scripts/logo.py from the cover of Cero's Code of Conduct PDF. Do not edit by hand.
// The wordmark's four letters and the two crescents of the ring, in one {w:.1f}×{h:.1f} frame.
export const LOGO_W = {w:.2f};
export const LOGO_H = {h:.2f};
export const LETTERS = {json.dumps({k: paths[k] for k in "cero"}, indent=2)} as const;
export const RING = {json.dumps({k: paths[k] for k in ("swirlA", "swirlB")}, indent=2)} as const;
// The ring's own box inside the logo frame (used to scale the ring up for the preloader and favicon).
export const RING_BOX = {{ x: {(rx0-x0)*S:.2f}, y: {(ry0-y0)*S:.2f}, w: {(rx1-rx0)*S:.2f}, h: {(ry1-ry0)*S:.2f} }};
'''
open("lib/logo.ts", "w").write(ts)

big = [drawings[12], drawings[13]]
bx0, by0 = min(b["rect"].x0 for b in big), min(b["rect"].y0 for b in big)
bx1, by1 = max(b["rect"].x1 for b in big), max(b["rect"].y1 for b in big)
svg = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {bx1-bx0:.1f} {by1-by0:.1f}">' + "".join(f'<path d="{to_d(b, bx0, by0)}"/>' for b in big) + "</svg>"
open("public/media/swirl.svg", "w").write(svg)

# Favicon: the ring in Sun on Navy.
fs = 64 / max(rx1 - rx0, ry1 - ry0) * 0.72
fav = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" rx="14" fill="#1E2470"/>' + "".join(
    f'<path fill="#FFCB3D" d="{to_d(drawings[parts[k]], rx0 - (64/fs - (rx1-rx0))/2, ry0 - (64/fs - (ry1-ry0))/2, fs)}"/>' for k in ("swirlA", "swirlB")) + "</svg>"
open("app/icon.svg", "w").write(fav)
print("logo", round(w, 1), round(h, 1))
