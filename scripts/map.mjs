// Builds public/media/europe-dots.svg and lib/europe-map.ts: a dot-matrix map of Europe (the treatment of
// virya-energy.com's "Worldwide impact" map) with Cero's five case-study projects, the Bumble Bee project from the
// newsroom and the six offices from /contact, projected once at build time so the page ships plain SVG.
//
// Land: Natural Earth 1:50m via world-atlas (countries-50m.json). Projection: conic conformal centred on Europe.
// Dots sit on a square grid every STEP px and are kept where their centre falls on land.
// Positions: town centres of each project location as named on its live /project/ page, and each office address.
// Run: node scripts/map.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { feature } from "topojson-client";
import { geoConicConformal, geoContains, geoPath } from "d3-geo";

const W = 900, H = 720, STEP = 9, R = 2.6;
const frame = { type: "Polygon", coordinates: [[[-11, 35], [-11, 59.5], [27, 59.5], [27, 35], [-11, 35]]] };
const topo = JSON.parse(readFileSync("node_modules/world-atlas/countries-50m.json", "utf8"));
const land = feature(topo, topo.objects.countries).features;
const projection = geoConicConformal().rotate([-8, 0]).center([0, 47.5]).parallels([40, 56]).fitExtent([[10, 10], [W - 10, H - 10]], frame);

const dots = [];
for (let y = STEP / 2; y < H; y += STEP) for (let x = STEP / 2; x < W; x += STEP) {
  const ll = projection.invert([x, y]);
  if (ll && land.some((f) => geoContains(f, ll))) dots.push([x, y]);
}

// [name, lon, lat]
const sites = [
  { id: "pontinia", name: "Pontinia", place: "Latina, Italy", lon: 13.05, lat: 41.41 },
  { id: "delfini", name: "Delfini", place: "Prosotsani Drama, Greece", lon: 24.06, lat: 41.18 },
  { id: "castrum", name: "Castrum", place: "Montalto di Castro, Italy", lon: 11.61, lat: 42.35 },
  { id: "bolotana", name: "Bolotana", place: "Sardinia, Italy", lon: 8.96, lat: 40.31 },
  { id: "larks-green", name: "Larks Green", place: "South Gloucestershire, England", lon: -2.48, lat: 51.56 },
  { id: "bumble-bee", name: "Bumble Bee", place: "West Burton, near Doncaster, England", lon: -0.81, lat: 53.36 },
];
const offices = [
  { id: "london", name: "London", lon: -0.089, lat: 51.524 },
  { id: "madrid", name: "Madrid", lon: -3.694, lat: 40.425 },
  { id: "hamburg", name: "Hamburg", lon: 9.99, lat: 53.548 },
  { id: "warsaw", name: "Warsaw", lon: 21.006, lat: 52.234 },
  { id: "milan", name: "Milan", lon: 9.187, lat: 45.476 },
  { id: "lyon", name: "Lyon", lon: 4.857, lat: 45.778 },
];
const place = (p) => { const [x, y] = projection([p.lon, p.lat]); return { ...p, x: +x.toFixed(1), y: +y.toFixed(1) }; };

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}"><g fill="#1E2470">` +
  dots.map(([x, y]) => `<circle cx="${x}" cy="${y}" r="${R}"/>`).join("") + `</g></svg>`;
writeFileSync("public/media/europe-dots.svg", svg);
writeFileSync("lib/europe-map.ts", `// Generated by scripts/map.mjs. Do not edit by hand.
// Dots: public/media/europe-dots.svg (${dots.length} dots, Natural Earth 1:50m, conic conformal). Pins: projected into the same ${W}×${H} frame.
export const MAP_W = ${W};
export const MAP_H = ${H};
export const SITE_POINTS = ${JSON.stringify(sites.map(place), null, 2)};
export const OFFICE_POINTS = ${JSON.stringify(offices.map(place), null, 2)};
`);
console.log(dots.length, "dots;", sites.map(place).map((p) => `${p.name} ${p.x},${p.y}`).join(" | "));
